"""Adapter for the FAA CARI-7 program (menu-less batch mode).

Facts used here were verified in the official package (cari_7exe.zip) and the
CARI-7 User's Guide (DOT/FAA/AM-21/6), and in the distributed source code:

* Batch mode: CARI.INI ``MENUS = NO!``; DEFAULT.INP lines 1-5 = date override,
  hour, particle, tally, file. A file name ``*.DEG`` processes every DEG file in
  the working directory (``ls -1`` via CALL SYSTEM when ``OS`` is not WIN).
* DEG format: line 1 ``MM/YYYY, name``; line 2 header; then
  ``deg, min, N/S, deg, min, E/W, feet, minutes`` per waypoint.
* ``DEG_FLT_DOSE`` builds one step per minute, evaluated at the half minute,
  with geodesic interpolation between waypoints and linear altitude; the
  flight dose is ``sum(rate/60)``. The .DAT step table gives the rate (µSv/h for
  dose tallies) and the running total (µSv). Trip length limit: 2000 minutes.
* Altitude in feet is converted to atmospheric depth with ATMOSPHERE/FT-GM.DAT
  (U.S. Standard Atmosphere 1976, geopotential altitude).
* CARI-7 forces GCR model 4 (ISO 2004 LIS modulated by the CARI-6
  heliocentric potential), no superposition and NVCR = 0 (GETINI).
* CARI.INI keys are matched on their first two characters; a ``DIAGNOSE``
  line would set DISPLAY, so it is not written.
* CARI writes into AIRPORTS/, DIAGNOSE/, GCR_MODELS/ and the working
  directory, so each batch runs in its own working directory.
* CARI does many small file reads and writes. Through a host bind mount
  (virtiofs in Colima/Docker Desktop) that dominates the run time, so by
  default (``docker_local_copy``) the docker runner copies the data
  directories and the batch inputs into the container's own filesystem, runs
  there and copies the outputs back. Measured on SCL->PUQ: 40 s -> 4 s with
  byte-identical .SUM/.DAT.
"""


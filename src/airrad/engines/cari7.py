ENGINE_NAME = "CARI-7"
COPIED_DIRS = ("AIRPORTS", "ATMOSPHERE", "DIAGNOSE", "GCR_MODELS", "SOLARMOD")
LINKED_DIRS = ("CUTOFFS", "FORBUSH", "KP_INDEX", "SHOWERS")
MAX_TRIP_MIN = 2000
MAX_ALT_FT = 300_000
UNIT_MAP = {"microSv": "µSv", "microGy": "µGy"}
CONTAINER_INSTALL = "/opt/cari7"
CONTAINER_WORK = "/work"
CONTAINER_LOCAL = "/tmp/cari_run"
# Outputs copied back from the container-local run directory (besides *.SUM, *.DAT).
RETURNED_FILES = ("FILELIST.TXT", "fort.40", "DEBUGGER.DAT")

CARI_INI = (
    "VIEWER    = cat         \n"
    "OS        = UNIX        \n"
    "MENUS     = NO!         \n"
    "CARI7.RPT = NO!         \n"
    "END       = END\n"
    "\nGenerated by airrad. Keys are read as A10,A2,A12 up to END (see GETINI in cari7.f).\n"
)


class CariError(RuntimeError):
    pass


@dataclass
class Cari7Config:
    install_dir: Path
    executable: str = "cari-7_linux_intel_exe"
    runner: str = "docker"  # "docker" | "native"
    docker_image: str = "debian:bookworm-slim"
    docker_platform: str = "linux/amd64"
    timeout_s: int = 3600
    max_parallel: int = 1
    flights_per_batch: int | None = None  # default: split each group evenly over max_parallel
    docker_local_copy: bool = True  # run inside the container filesystem instead of the bind mount

    @classmethod
    def from_dict(cls, d: dict, base: Path) -> "Cari7Config":
        install = Path(d["install_dir"])
        if not install.is_absolute():
            install = (base / install).resolve()
        return cls(
            install_dir=install,
            executable=d.get("executable", cls.executable),
            runner=d.get("runner", cls.runner),
            docker_image=d.get("docker_image", cls.docker_image),
            docker_platform=d.get("docker_platform", cls.docker_platform),
            timeout_s=int(d.get("timeout_s", cls.timeout_s)),
            max_parallel=int(d.get("max_parallel", cls.max_parallel)),
            flights_per_batch=d.get("flights_per_batch"),
            docker_local_copy=bool(d.get("docker_local_copy", cls.docker_local_copy)),
        )


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def sha256_tree(path: Path) -> str:
    """Hash of (relative path, file hash) pairs; order independent of the filesystem."""
    h = hashlib.sha256()
    for f in sorted(p for p in path.rglob("*") if p.is_file()):
        h.update(f.relative_to(path).as_posix().encode())
        h.update(sha256_file(f).encode())
    return h.hexdigest()


def elf_machine(path: Path) -> str:
    with open(path, "rb") as fh:
        head = fh.read(20)
    if head[:4] != b"\x7fELF":
        return "not-ELF"
    machine = int.from_bytes(head[18:20], "little")
    return {0x3E: "x86-64", 0xB7: "aarch64", 0x03: "x86"}.get(machine, f"e_machine={machine:#x}")


def _last_data_line(path: Path) -> str:
    text = path.read_text(encoding="latin-1").replace("\x1a", "")  # DOS end-of-file marker
    lines = [ln.strip() for ln in text.splitlines() if ln.strip()]
    return lines[-1] if lines else ""


def format_deg_coord(value: float, pos: str, neg: str) -> tuple[int, str, str]:
    """Signed decimal degrees -> (integer degrees, minutes text, hemisphere)."""
    hemi = pos if value >= 0 else neg
    units = int(round(abs(value) * 60 * 10_000))  # 1e-4 arc-minute (~0.2 m)
    deg, rem = divmod(units, 60 * 10_000)
    return deg, f"{rem / 10_000:.4f}", hemi


def write_deg(path: Path, title: str, year: int, month: int, t_min, lat, lon, alt_ft) -> None:
    t = np.asarray(t_min, dtype=float)
    if not np.allclose(t, np.round(t)):
        raise CariError("Los waypoints DEG requieren minutos enteros")
    t = np.round(t).astype(int)
    if t[0] != 0:
        raise CariError("El primer waypoint DEG debe estar en el minuto 0 (CARI integra desde el minuto 1)")
    if np.any(np.diff(t) <= 0):
        raise CariError("Minutos de waypoint no estrictamente crecientes")
    if t[-1] > MAX_TRIP_MIN:
        raise CariError(f"Duración {t[-1]} min excede el límite de CARI-7 ({MAX_TRIP_MIN} min)")
    alt = np.asarray(alt_ft, dtype=float)
    if np.any(alt > MAX_ALT_FT) or np.any(alt < -600):
        raise CariError("Altitud fuera del rango de CARI-7 (-600 a 300000 ft)")
    if not 1 <= month <= 12:
        raise CariError("Mes inválido")
    title = re.sub(r"[^A-Za-z0-9_\-]", "_", title)[:28]
    lines = [f"{month:02d}/{year:04d}, {title}", "DEG MIN N/S DEG MIN E/W FEET TIME(MIN)"]
    for ti, la, lo, a in zip(t, lat, lon, alt):
        ld, lm, ns = format_deg_coord(float(la), "N", "S")
        od, om, ew = format_deg_coord(float(lo), "E", "W")
        lines.append(f"{ld}, {lm}, {ns}, {od}, {om}, {ew}, {int(round(a))}, {ti}")
    path.write_text("\r\n".join(lines) + "\r\n", encoding="ascii")


_SUM_DOSE = re.compile(r"^\s*([-+0-9.Ee]+)\s+(\S+)\s+(micro\w+|p/sq\.cm|counts),\s*(.+?)\s*$")
_DAT_ROW = re.compile(r"^\s*([-0-9.]+)\s+([-0-9.]+)\s+([-0-9.]+)\s+(\d+)\s+([-+0-9.Ee]+)\s+([-+0-9.Ee]+)\s*$")


def parse_sum(path: Path) -> dict:
    text = path.read_text(encoding="latin-1")
    out: dict = {}
    m = re.search(r"GCR MODEL:?\s*(\d+)\s+TRANSPORT AND CUTOFFS:\s*(\S+)\s+SUPERPOSITION:\s*(\d+)", text)
    if m:
        out.update(gcr_model=int(m[1]), nvcr=m[2], superposition=int(m[3]))
    m = re.search(r"DATE:\s*(\d{4}/\d{2}/\d{2})\s+HOUR:\s*(\d+)", text)
    if m:
        out.update(date=m[1], hour=int(m[2]))
    last = _last_data_line(path)
    m = _SUM_DOSE.match(last)
    if not m:
        raise CariError(f"{path.name}: CARI no reportó una dosis ({last!r})")
    out.update(total=float(m[1]), particle=m[2], unit_raw=m[3], quantity_label=m[4].strip())
    return out


def parse_dat(path: Path) -> pd.DataFrame:
    rows = []
    for line in path.read_text(encoding="latin-1").splitlines():
        m = _DAT_ROW.match(line)
        if m:
            rows.append([float(m[1]), float(m[2]), float(m[3]), int(m[4]), float(m[5]), float(m[6])])
    df = pd.DataFrame(rows, columns=["lat", "lon_raw", "depth_g_cm2", "step", "rate", "cum_dose"])
    df["lon"] = (df["lon_raw"] + 180.0) % 360.0 - 180.0
    df["t_start_min"] = df["step"] - 1.0
    df["t_mid_min"] = df["step"] - 0.5
    df["t_end_min"] = df["step"].astype(float)
    return df


def load_ft_gm_table(install_dir: Path) -> pd.DataFrame:
    """CARI's altitude (kft) -> depth (g/cm2) table, for consistency checks."""
    rows = []
    for line in (install_dir / "ATMOSPHERE" / "FT-GM.DAT").read_text().splitlines()[1:]:
        parts = [p.strip() for p in line.split(",")]
        if len(parts) >= 2:
            try:
                rows.append((float(parts[0]) * 1000.0, float(parts[1])))
            except ValueError:
                continue
    return pd.DataFrame(rows, columns=["alt_ft", "depth_g_cm2"])


class Cari7Engine:
    name = ENGINE_NAME

    def __init__(self, cfg: Cari7Config):
        self.cfg = cfg
        self.install = cfg.install_dir
        self.exe = self.install / cfg.executable

    # ------------------------------------------------------------------ checks
    def check_installation(self) -> list[str]:
        problems = []
        if not self.exe.is_file():
            problems.append(f"No existe el ejecutable {self.exe}")
        elif not os.access(self.exe, os.X_OK):
            problems.append(f"El ejecutable no tiene permiso de ejecución: {self.exe}")
        for d in COPIED_DIRS + LINKED_DIRS:
            if not (self.install / d).is_dir():
                problems.append(f"Falta el directorio de datos {d}/")
        if self.exe.is_file() and elf_machine(self.exe) != "x86-64":
            problems.append(f"Arquitectura inesperada del binario: {elf_machine(self.exe)}")
        if self.cfg.runner == "native" and platform.machine() not in ("x86_64", "AMD64"):
            problems.append(f"runner=native en host {platform.machine()}: el binario es Linux x86-64")
        if self.cfg.runner == "docker" and shutil.which("docker") is None:
            problems.append("runner=docker pero no se encontró el comando docker")
        if self.cfg.runner == "docker" and platform.system() == "Darwin":
            home = Path.home().resolve()
            if home not in self.install.resolve().parents:
                problems.append("En macOS (Colima/Docker Desktop) la instalación debe estar bajo $HOME para montarse")
        return problems

    def describe(self) -> dict:
        exe_bytes = self.exe.read_bytes()
        banner = re.search(rb"([A-Z][a-z]+ \d{1,2}, \d{4} \(\d+\.\d+\.\d+\))", exe_bytes)
        data = {}
        for d in COPIED_DIRS + LINKED_DIRS:
            data[d] = sha256_tree(self.install / d)
        mv = self.install / "SOLARMOD" / "MV-DATES.L99"
        kp = self.install / "KP_INDEX" / "KP_INDEX.TXT"
        fb = self.install / "FORBUSH" / "FORBUSH.DAT"
        return {
            "engine": ENGINE_NAME,
            "executable": self.cfg.executable,
            "executable_sha256": hashlib.sha256(exe_bytes).hexdigest(),
            "executable_size": len(exe_bytes),
            "executable_arch": elf_machine(self.exe),
            "embedded_banner": banner.group(1).decode() if banner else None,
            "fixed_model_options": {
                "gcr_model": "4 = ISO 2004 LIS modulado por potencial heliocéntrico CARI-6 (forzado en CARI-7)",
                "superposition": "0 (forzado en CARI-7)",
                "nvcr": "0 = rigidez de corte aparente ajustada por altitud, flujo isótropo (forzado)",
                "cutoff_grids": "WGRC1965, IGRF1980, DGRF1990, IGRF1995, IGRF2000, IGRF2010; desde 2010 se usa IGRF2010 sin extrapolar",
                "atmosphere": "U.S. Standard Atmosphere 1976 (ATMOSPHERE/FT-GM.DAT)",
                "vehicle_shielding": "ninguno",
            },
            "data_tree_sha256": data,
            "data_files": {
                "SOLARMOD/MV-DATES.L99": {"sha256": sha256_file(mv), "last_entry": _last_data_line(mv)},
                "SOLARMOD/MORDATES.2K": {"sha256": sha256_file(self.install / "SOLARMOD" / "MORDATES.2K")},
                "KP_INDEX/KP_INDEX.TXT": {"sha256": sha256_file(kp), "last_entry": _last_data_line(kp)[:8]},
                "FORBUSH/FORBUSH.DAT": {"sha256": sha256_file(fb)},
            },
            "runner": self.cfg.runner,
            "docker_image": self.cfg.docker_image if self.cfg.runner == "docker" else None,
            "docker_platform": self.cfg.docker_platform if self.cfg.runner == "docker" else None,
            "docker_local_copy": self._local_copy,
            "host": {"system": platform.system(), "machine": platform.machine(), "release": platform.release()},
        }

    def heliocentric_potential(self, year: int, month: int) -> int | None:
        """Monthly heliocentric potential (MV) from MV-DATES.L99, if present."""
        pat = re.compile(rf"^\s*{month:02d}/{year:04d},\s*(\d+)")
        for line in (self.install / "SOLARMOD" / "MV-DATES.L99").read_text().splitlines():
            m = pat.match(line)
            if m:
                return int(m[1])
        return None

    def mordates_overrides(self) -> list[str]:
        return [ln.strip() for ln in (self.install / "SOLARMOD" / "MORDATES.2K").read_text().splitlines() if ln.strip()]

    def run_official_example(self, work: Path) -> dict:
        """Run Examples/EXAMPLE.DEG and compare with the distributed reference output."""
        self._prepare_workdir(work)
        shutil.copy2(self.install / "Examples" / "EXAMPLE.DEG", work / "EXAMPLE.DEG")
        (work / "DEFAULT.INP").write_text("0000/00/00\n 0 \n 0 \n 2 \nEXAMPLE.DEG\n", encoding="ascii")
        info = self._run_cmd(work)
        self._cleanup_workdir(work)
        ref_sum = parse_sum(self.install / "Examples" / "EXAMPLE.SUM")
        ref_dat = parse_dat(self.install / "Examples" / "EXAMPLE.DAT")
        got_sum = parse_sum(work / "EXAMPLE.SUM")
        got_dat = parse_dat(work / "EXAMPLE.DAT")
        cols = ["lat", "lon_raw", "depth_g_cm2", "step", "rate", "cum_dose"]
        same_shape = ref_dat.shape == got_dat.shape
        max_rel = (
            float(np.nanmax(np.abs(got_dat[cols].to_numpy() / ref_dat[cols].replace(0, np.nan).to_numpy() - 1)))
            if same_shape
            else None
        )
        return {
            "example": "Examples/EXAMPLE.DEG (01/2002, FL-27), tally ICRP 103 effective dose",
            "reference_total_uSv": ref_sum["total"],
            "computed_total_uSv": got_sum["total"],
            "reference_label": ref_sum["quantity_label"],
            "computed_label": got_sum["quantity_label"],
            "n_steps_reference": len(ref_dat),
            "n_steps_computed": len(got_dat),
            "max_relative_difference_steps": max_rel,
            "identical": bool(same_shape and max_rel == 0.0 and ref_sum["total"] == got_sum["total"]),
            "parser_cum_equals_sum": bool(np.isclose(got_dat["cum_dose"].iloc[-1], got_sum["total"])),
            "parser_rate_integral_uSv": float((got_dat["rate"] / 60.0).sum()),
            "run": info,
        }

    # ------------------------------------------------------------------- run
    @property
    def _local_copy(self) -> bool:
        return self.cfg.runner == "docker" and self.cfg.docker_local_copy

    def _prepare_workdir(self, work: Path) -> None:
        work.mkdir(parents=True, exist_ok=False)
        (work / "CARI.INI").write_text(CARI_INI, encoding="ascii")
        if self._local_copy:  # data directories are copied inside the container (_command)
            return
        for d in COPIED_DIRS:
            shutil.copytree(self.install / d, work / d)
        target_root = CONTAINER_INSTALL if self.cfg.runner == "docker" else str(self.install)
        for d in LINKED_DIRS:
            os.symlink(f"{target_root}/{d}", work / d)

    def _cleanup_workdir(self, work: Path) -> None:
        """Remove copies of the installation data (hashed in describe()); keep inputs/outputs."""
        for d in LINKED_DIRS:
            (work / d).unlink(missing_ok=True)
        gcr = work / "GCR_MODELS" / "ISO_GCR2.OUT"
        if gcr.exists():
            shutil.copy2(gcr, work / "ISO_GCR2.OUT")  # GCR spectrum written for this batch's date
        for d in COPIED_DIRS:
            shutil.rmtree(work / d, ignore_errors=True)

    def _local_script(self) -> str:
        """Shell script: copy data + inputs into the container, run CARI there, copy outputs back.

        Only the data directories are copied (never the installation root, whose
        EXAMPLE.DEG would otherwise be picked up by ``*.DEG``).
        """
        L, I, W = CONTAINER_LOCAL, CONTAINER_INSTALL, CONTAINER_WORK
        dirs = " ".join(COPIED_DIRS + LINKED_DIRS)
        back = " ".join(RETURNED_FILES)
        return (
            f"set -e; mkdir -p {L}; cd {I}; cp -R {dirs} {L}/; "
            f"cd {W}; for f in *; do if [ -f \"$f\" ]; then cp \"$f\" {L}/; fi; done; "
            f"cd {L}; set +e; {I}/{self.cfg.executable}; rc=$?; set -e; "
            f"for f in *.SUM *.DAT {back}; do if [ -f \"$f\" ]; then cp \"$f\" {W}/; fi; done; "
            f"if [ -f GCR_MODELS/ISO_GCR2.OUT ]; then cp GCR_MODELS/ISO_GCR2.OUT {W}/ISO_GCR2.OUT; fi; "
            f"exit $rc"
        )

    def _command(self, work: Path) -> list[str]:
        if self._local_copy:
            return [
                "docker", "run", "--rm", "--platform", self.cfg.docker_platform,
                "-v", f"{self.install}:{CONTAINER_INSTALL}:ro",
                "-v", f"{work.resolve()}:{CONTAINER_WORK}",
                self.cfg.docker_image,
                "sh", "-c", self._local_script(),
            ]  # fmt: skip
        if self.cfg.runner == "docker":
            return [
                "docker", "run", "--rm", "--platform", self.cfg.docker_platform,
                "-v", f"{self.install}:{CONTAINER_INSTALL}:ro",
                "-v", f"{work.resolve()}:{CONTAINER_WORK}",
                "-w", CONTAINER_WORK,
                self.cfg.docker_image,
                f"{CONTAINER_INSTALL}/{self.cfg.executable}",
            ]  # fmt: skip
        return [str(self.exe)]

    def _run_batch(self, work: Path, tally: int) -> dict:
        (work / "DEFAULT.INP").write_text(f"0000/00/00\n 0 \n 0 \n {tally} \n*.DEG\n", encoding="ascii")
        return self._run_cmd(work)

    def _run_cmd(self, work: Path) -> dict:
        cmd = self._command(work)
        started = datetime.now(timezone.utc)
        proc = subprocess.run(
            cmd, cwd=work, stdin=subprocess.DEVNULL, capture_output=True, text=True, timeout=self.cfg.timeout_s
        )
        finished = datetime.now(timezone.utc)
        (work / "cari_stdout.log").write_text(proc.stdout + "\n--- stderr ---\n" + proc.stderr)
        info = {
            "command": cmd,
            "returncode": proc.returncode,
            "started_utc": started.isoformat(timespec="seconds"),
            "finished_utc": finished.isoformat(timespec="seconds"),
            "wall_s": (finished - started).total_seconds(),
        }
        if proc.returncode != 0:
            raise CariError(f"CARI terminó con código {proc.returncode}; ver {work / 'cari_stdout.log'}")
        return info

    def run(self, requests: list[FlightRequest], run_dir: Path) -> list[FlightResult]:
        problems = self.check_installation()
        if problems:
            raise CariError("Instalación de CARI-7 no utilizable:\n- " + "\n- ".join(problems))
        # A batch shares DEFAULT.INP (tally) and the GCR spectrum file (date), so batches are
        # keyed by (tally, year, month) and split into chunks to use several CPUs.
        groups: dict[tuple, list[FlightRequest]] = {}
        for r in requests:
            groups.setdefault((r.quantity, r.year, r.month), []).append(r)
        batches = []
        n_par = max(1, self.cfg.max_parallel)
        for (q, y, m), reqs in sorted(groups.items(), key=lambda kv: (kv[0][0].info.key, kv[0][1], kv[0][2])):
            size = self.cfg.flights_per_batch or -(-len(reqs) // n_par)
            for c in range(0, len(reqs), size):
                work = Path(run_dir) / "cari_work" / f"B{len(batches):02d}_{q.info.key}_{y:04d}{m:02d}"
                batches.append((work, q, y, m, reqs[c : c + size]))

        def do(batch):
            work, q, y, m, reqs = batch
            self._prepare_workdir(work)
            names, warn_by_id, tripmin = {}, {}, {}
            for i, r in enumerate(reqs):
                traj = r.trajectory
                w = list(traj.warnings)
                if not traj.has_integer_minutes:
                    traj = traj.resample_minutes(1)
                    w = list(traj.warnings) + ["Trayectoria remuestreada a 1 min para CARI-7."]
                alt_ft, aw = traj.cari_altitude_ft()
                stem = f"S{i:04d}"
                p = traj.points
                write_deg(work / f"{stem}.DEG", r.scenario_id, y, m, p["t_min"], p["lat"], p["lon"], alt_ft)
                names[r.scenario_id] = stem
                warn_by_id[r.scenario_id] = w + aw
                tripmin[r.scenario_id] = int(round(p["t_min"].iloc[-1]))
            info = self._run_batch(work, q.info.cari_tally)
            self._cleanup_workdir(work)
            return work, q, y, m, reqs, names, warn_by_id, tripmin, info

        with ThreadPoolExecutor(max_workers=max(1, self.cfg.max_parallel)) as ex:
            done = list(ex.map(do, batches))

        results = []
        for work, q, y, m, reqs, names, warn_by_id, tripmin, info in done:
            for r in reqs:
                sid = r.scenario_id
                results.append(self._collect(work, names[sid], r, q, y, m, warn_by_id[sid], tripmin[sid], info))
        return results

    def _collect(self, work, stem, req, q, y, m, warnings, expected_steps, info) -> FlightResult:
        sum_path, dat_path = work / f"{stem}.SUM", work / f"{stem}.DAT"
        if not sum_path.exists():
            raise CariError(f"{req.scenario_id}: CARI no generó {sum_path.name}")
        s = parse_sum(sum_path)
        unit = UNIT_MAP.get(s["unit_raw"], s["unit_raw"])
        if unit != q.info.dose_unit or s["quantity_label"] != q.info.cari_label:
            raise CariError(f"{req.scenario_id}: magnitud inesperada {s['unit_raw']}, {s['quantity_label']!r}")
        if s.get("date") != f"{y:04d}/{m:02d}/00":
            raise CariError(f"{req.scenario_id}: CARI usó la fecha {s.get('date')} en lugar de {y:04d}/{m:02d}/00")
        steps = parse_dat(dat_path)
        p = req.trajectory.points
        if len(steps) != expected_steps:
            raise CariError(f"{req.scenario_id}: {len(steps)} pasos en .DAT, se esperaban {expected_steps}")
        if not np.isclose(steps["cum_dose"].iloc[-1], s["total"], rtol=5e-4):
            raise CariError(f"{req.scenario_id}: total .DAT {steps['cum_dose'].iloc[-1]} ≠ .SUM {s['total']}")
        ts0 = p["timestamp_utc"].iloc[0]
        steps["timestamp_mid_utc"] = ts0 + pd.to_timedelta(steps["t_mid_min"], unit="min")
        steps["quantity"] = q.info.key
        hp = self.heliocentric_potential(y, m)
        conditions = {
            **{k: s.get(k) for k in ("gcr_model", "nvcr", "superposition", "date", "hour")},
            "averaging": "promedio mensual (dd=00): sin ajustes horarios de Forbush ni Kp",
            "heliocentric_potential_MV": hp,
            "batch": info,
        }
        if hp is None:
            warnings = warnings + [f"Sin potencial heliocéntrico para {m:02d}/{y}; CARI usa el más reciente disponible."]
        return FlightResult(
            scenario_id=req.scenario_id,
            quantity=q,
            engine=ENGINE_NAME,
            total_dose=s["total"],
            steps=steps,
            raw_files={"deg": work / f"{stem}.DEG", "sum": sum_path, "dat": dat_path, "log": work / "cari_stdout.log"},
            warnings=warnings,
            conditions=conditions,
        )
